/** Exercise dashboard settings and palette failure boundaries before source-editor scenarios. */
async function settingsWorkflow(page, baseline) {
    await page.getByRole('button', { name: 'Saved layout', exact: true }).click()
    await page.getByRole('region', { name: 'Saved layout' }).getByLabel('Columns', { exact: true }).fill('8')
    await page.getByRole('region', { name: 'Saved layout' }).getByLabel('Rows', { exact: true }).fill('8')
    await page.locator('#dashboard[data-ready=true]').waitFor()
    await page.getByRole('region', { name: 'Saved layout' }).getByLabel('Background color', { exact: true }).fill('#123456')
    const settingsBytes = await saved(page)
    assert.deepEqual(JSON.parse(settingsBytes).grid, { columns: 8, rows: 8, color: 'rgb(18, 52, 86)' })
    await page.getByLabel('Load layout', { exact: true }).setInputFiles({ name: 'settings.json', mimeType: 'application/json', buffer: Buffer.from(settingsBytes) })
    await page.locator('#dashboard[data-ready=true]').waitFor()
    assert.equal(await page.getByRole('region', { name: 'Saved layout' }).getByLabel('Background color', { exact: true }).inputValue(), '#123456')
    assert.equal(await page.getByRole('region', { name: 'Saved layout' }).getByLabel('Columns', { exact: true }).inputValue(), '8')
    assert.equal(await saved(page), settingsBytes, 'dimensions and background survive edit/save/reload')
    await page.getByRole('button', { name: 'Close settings' }).click()
    // A failed preset leaves successful previews usable, and the root palette cannot consume a dashboard widget.
    await page.route('**/SandBoxWidgets/Graph.json', route => route.fulfill({ status: 404, body: 'missing fixture' }))
    await palette(page)
    assert.equal(await page.locator('.widget-gallery > .grid-stack > .grid-stack-item').count(), 9)
    await page.getByRole('alert').filter({ hasText: 'Widget unavailable (404)' }).waitFor()
    await page.getByRole('button', { name: 'Dismiss error' }).click()
    const originalWidget = page.locator('#dashboard > .grid-stack-item:has(> .widget-frame-content)')
    const originalBounds = await originalWidget.boundingBox()
    const forbiddenBounds = await page.getByLabel('Preview Value', { exact: true }).boundingBox()
    await page.mouse.move(originalBounds.x + 30, originalBounds.y + 25); await page.mouse.down()
    await page.mouse.move(forbiddenBounds.x + 30, forbiddenBounds.y + 25, { steps: 30 }); await page.mouse.up()
    await page.getByRole('button', { name: 'Close palette' }).click()
    assert.equal(await page.locator('#dashboard > .grid-stack-item').count(), 2)
    const afterForbiddenDrop = JSON.parse(await saved(page))
    assert.ok(Object.values(afterForbiddenDrop.widgets).some(widget => widget.options.about?.name === 'Controlled fixture' && widget.options.sandbox.includes('handle_msg')))
    await page.getByRole('button', { name: 'Close settings' }).click()
    await page.unroute('**/SandBoxWidgets/Graph.json')
    await page.getByRole('button', { name: 'Saved layout', exact: true }).click()
    await page.getByLabel('Load layout', { exact: true }).setInputFiles({ name: 'baseline.json', mimeType: 'application/json', buffer: Buffer.from(baseline) })
    await page.waitForFunction(() => document.querySelector('#dashboard').style.backgroundColor === 'rgb(255, 255, 255)' && document.querySelector('#dashboard').dataset.ready === 'true')
    await page.getByRole('button', { name: 'Close settings' }).click()
}

/** Exercise real editor input, pointer geometry, round trips and disposal in each server mode. */
