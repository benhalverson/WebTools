    await page.mouse.move(resize.x + resize.width / 2, resize.y + resize.height / 2)
    await page.mouse.down()
    await page.mouse.move(resize.x - 200, resize.y - 120, { steps: 20 })
    await page.mouse.up()
    await page.waitForFunction(previous => document.querySelector('#dashboard > .grid-stack-item:has(> .widget-frame-content)').getAttribute('gs-w') !== previous, width)
    await item.focus()
    await page.keyboard.press('Enter')
    await page.getByRole('region', { name: 'Widget settings' }).waitFor()
    await page.getByLabel('Width', { exact: true }).fill('2')
    await page.getByLabel('Height', { exact: true }).fill('2')
    await page.getByRole('region', { name: 'Widget settings' }).locator('input[name="data[gain]"]').fill('7')
    console.log('editor: configuration / source')
    await page.getByRole('button', { name: 'Edit source and form', exact: true }).click()
    const source = page.locator('.code-editor .view-line').first()
    await source.waitFor()
    await page.getByLabel('Edit preview', { exact: true }).check()
    const previewItem = page.locator('.source-editor-preview .grid-stack > .grid-stack-item').first()
    const previewResize = await previewItem.locator('.ui-resizable-se').boundingBox()
    const previewWidth = await previewItem.getAttribute('gs-w')
    await page.mouse.move(previewResize.x + previewResize.width / 2, previewResize.y + previewResize.height / 2); await page.mouse.down()
    await page.mouse.move(previewResize.x + previewResize.width / 2 + 125, previewResize.y + previewResize.height / 2, { steps: 20 }); await page.mouse.up()
    await page.waitForFunction(previous => document.querySelector('.source-editor-preview .grid-stack > .grid-stack-item').getAttribute('gs-w') !== previous, previewWidth)
    await previewItem.focus(); await page.keyboard.press('Enter')
