import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

/** Read actual browser download bytes rather than reaching into React state. */
async function saved(page) {
    await page.getByRole('button', { name: 'Saved layout', exact: true }).click()
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Save layout', exact: true }).click()
    return readFile(await (await pending).path(), 'utf8')
}

/** Wait for live palette previews before starting another user action or injected operation. */
async function palette(page) {
    await page.getByRole('button', { name: 'Add widget', exact: true }).click()
    await page.locator('.widget-gallery [data-ready=true]').waitFor()
    assert.equal(await page.getByLabel('Preview Subgrid', { exact: true }).getAttribute('title'), 'Subgrid\nNestable sub grid widget')
}

