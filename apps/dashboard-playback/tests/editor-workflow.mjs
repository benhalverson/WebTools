    await page.locator('.formbuilder .builder-component').last().hover()
    await page.locator('.formbuilder .builder-component').last().locator('[ref="removeComponent"]').click()
    await page.getByRole('button', { name: 'Apply and close', exact: true }).click()
    // Builder failures remain visible above the modal and do not damage the original widget.
    await page.evaluate(() => {
        const build = Formio.builder.bind(Formio)
        Formio.builder = () => { Formio.builder = build; return Promise.reject(new Error('Injected builder failure')) }
    })
    await page.getByRole('button', { name: 'Edit source and form', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Injected builder failure' }).waitFor()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Dismiss error' }).click()
    // A builder resolving after cancellation must destroy itself without reopening the editor.
    await page.evaluate(() => {
        const build = Formio.builder.bind(Formio)
        window.closedLateBuilder = 0
        Formio.builder = (...args) => new Promise((resolve, reject) => {
            window.releaseBuilder = async () => {
                Formio.builder = build
                try {
                    const builder = await build(...args)
                    const destroy = builder.destroy.bind(builder)
                    builder.destroy = () => { window.closedLateBuilder++; destroy() }
                    resolve(builder)
                } catch (error) { reject(error) }
            }
        })
    })
    await page.getByRole('button', { name: 'Edit source and form', exact: true }).click()
    await page.waitForFunction(() => typeof window.releaseBuilder === 'function')
