    await page.getByRole('button', { name: 'Saved layout', exact: true }).click()
    await page.getByLabel('Load layout', { exact: true }).setInputFiles({ name: 'edit.json', mimeType: 'application/json', buffer: Buffer.from(baseline) })
    await page.locator('#dashboard[data-ready=true]').waitFor()
    await page.getByRole('button', { name: 'Close settings' }).click()
    await page.getByLabel('Enable widget edit', { exact: true }).check()
    await nestedExportWorkflow(page, original, baseline)
    await settingsWorkflow(page, baseline)
    const item = page.locator('#dashboard > .grid-stack-item:has(> .widget-frame-content)')
    const bounds = await item.boundingBox()
    // Pointer drag into an empty lower row; the browser drives GridStack's real event handlers.
    await page.mouse.move(bounds.x + 40, bounds.y + 30)
    await page.mouse.down()
    await page.mouse.move(bounds.x + 40, bounds.y + bounds.height + 30, { steps: 20 })
    await page.mouse.up()
    await page.waitForFunction(() => Number(document.querySelector('#dashboard > .grid-stack-item:has(> .widget-frame-content)').getAttribute('gs-y')) > 0)
