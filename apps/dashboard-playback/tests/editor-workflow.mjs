    assert.equal(await page.locator('#dashboard > .grid-stack-item').count(), 2)
    console.log('editor: repeat create/remove and exact round trips passed')
    // Clear the existing child, then add an authoritative dynamic-field widget directly into its nested owner.
    const nested = page.locator('#dashboard > .grid-stack-item:has(> .grid-stack-item-content) .grid-stack-item').first()
